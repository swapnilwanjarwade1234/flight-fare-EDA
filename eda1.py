"""### Feature Engineering for Duration and its Impact on Price

To analyze the relationship between `Duration` and `Price`, we need to convert the `Duration` column from string format (e.g., '2h 50m') into a numerical format (total minutes).
"""

# Function to convert duration string to total minutes
def duration_to_minutes(duration):
    if pd.isnull(duration):
        return np.nan
    duration = str(duration).replace(' ', '') # Remove spaces
    hours = 0
    minutes = 0
    if 'h' in duration:
        h_index = duration.find('h')
        hours = int(duration[:h_index])
        duration = duration[h_index+1:]
    if 'm' in duration:
        m_index = duration.find('m')
        minutes = int(duration[:m_index])

    return hours * 60 + minutes

# Apply the function to create a new 'Duration_minutes' column
df['Duration_minutes'] = df['Duration'].apply(duration_to_minutes)

print("DataFrame info after converting Duration:")
print(df[['Duration', 'Duration_minutes']].head())
display(df.info())

